_current = "en"


def _normalize(code: str) -> str:
    """Turn 'es_ES.UTF-8', 'pt-BR' or 'zh_Hans_CN' into a language code like 'es'."""
    code = code.strip().strip('"').split(".")[0].split("@")[0].replace("-", "_").lower()
    return code.split("_")[0]


def _system_language_candidates() -> List[str]:
    candidates: List[str] = []
    if sys.platform == "win32":
        try:
            import ctypes
            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            name = locale.windows_locale.get(lang_id)
            if name:
                candidates.append(name)
        except Exception:  # noqa: BLE001 - fall back to the other sources
            pass
    elif sys.platform == "darwin":
        # GUI apps on macOS usually start without LANG, so ask the system.
        try:
            out = subprocess.run(["defaults", "read", "-g", "AppleLanguages"],
                                 capture_output=True, text=True, timeout=3).stdout
            candidates += re.findall(r"[A-Za-z]{2,3}(?:[-_][A-Za-z0-9]+)*", out)
        except Exception:  # noqa: BLE001
            pass
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var)
        if value:
            candidates += value.split(":")
    try:
        candidates.append(locale.getlocale()[0] or "")
    except ValueError:
        pass
    return candidates


def detect_system_language() -> str:
    for candidate in _system_language_candidates():
        code = _normalize(candidate)
        if code in STRINGS:
            return code
    return "en"


def set_language(code: str) -> str:
    """Activate a language ('system' = follow the OS). Returns the active code."""
    global _current
    _current = code if code in STRINGS else detect_system_language()
    return _current


def current_language() -> str:
    return _current


def t(key: str, **kwargs) -> str:
    text = STRINGS.get(_current, {}).get(key) or STRINGS["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text
